"""Agent definitions for the three design roles, for backends that support named agents.

The roles (wf-orchestrator, wf-creator, wf-verifier) already work with no installation: their
full instructions travel in the prompt (:func:`~agentflow.workflow.design_prompts.creator_prompt`
and friends). This module renders the SAME instructions as agent definition files, so a user
can install them where Claude Code or Kiro look for agents, and the designer then gets the
role as its system prompt and only the data as its message.

    python -m agentflow.workflow list
    python -m agentflow.workflow show claude wf-creator
    python -m agentflow.workflow install claude --to ~/.claude/agents

Nothing here writes outside a directory the caller names: there is no default install
location, and an existing file that differs is never overwritten without ``--force``.
The files shipped in the package (``agent_files/``) are generated from the prompts by
``generate`` and a test keeps them identical, so there is one source of truth.

Formats (from the providers' documentation): Claude Code reads Markdown with YAML
frontmatter from ``.claude/agents/``; Kiro reads ``.json`` (or ``.md``) from
``.kiro/agents/``. Codex has custom agents as TOML, but the SDK cannot select one by name
yet, so no Codex file is produced; a Codex designer simply gets the full prompt.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from agentflow.workflow.design_prompts import ROLES, role_description, role_system

__all__ = [
    "BACKENDS",
    "agent_name",
    "claude_inline_agents",
    "install_agents",
    "packaged_dir",
    "render_agents",
]

BACKENDS = ("claude", "kiro")
_GENERATED = "generated by agentflow.workflow from design_prompts.py; do not edit by hand"
# Designers only reason and answer JSON: keep mutating and network tools out of reach.
_CLAUDE_DENIED = "Bash, Write, Edit, NotebookEdit, WebFetch, WebSearch"


def agent_name(role: str) -> str:
    return f"wf-{role}"


def packaged_dir() -> Path:
    return Path(__file__).parent / "agent_files"


def _claude_md(role: str) -> str:
    return (
        "---\n"
        f"# {_GENERATED}\n"
        f"name: {agent_name(role)}\n"
        f"description: {role_description(role)}\n"
        f"disallowedTools: {_CLAUDE_DENIED}\n"
        "permissionMode: plan\n"
        "---\n\n"
        f"{role_system(role)}\n"
    )


def claude_inline_agents() -> str:
    """The roles as the JSON for ``claude --agents``: nothing is installed or written to disk."""
    return json.dumps(
        {
            agent_name(r): {"description": role_description(r), "prompt": role_system(r)}
            for r in ROLES
        },
        ensure_ascii=False,
    )


def _kiro_json(role: str) -> str:
    return (
        json.dumps(
            {
                "name": agent_name(role),
                "description": role_description(role),
                "prompt": role_system(role),
                "tools": [],
            },
            ensure_ascii=False,
            indent=2,
        )
        + "\n"
    )


def render_agents() -> dict[str, dict[str, str]]:
    """``{"claude": {"wf-creator.md": text, ...}, "kiro": {"wf-creator.json": text, ...}}``."""
    return {
        "claude": {f"{agent_name(r)}.md": _claude_md(r) for r in ROLES},
        "kiro": {f"{agent_name(r)}.json": _kiro_json(r) for r in ROLES},
    }


def install_agents(
    backend: str, target: Path | str, *, force: bool = False, dry_run: bool = False
) -> list[tuple[Path, str]]:
    """Write the definitions for ``backend`` into ``target`` (a directory the caller chose).

    Returns ``[(path, action)]`` with action ``created``, ``unchanged``, ``overwritten`` or
    ``skipped`` (an existing, different file without ``force``). ``dry_run`` reports without
    writing.
    """
    if backend not in BACKENDS:
        raise ValueError(f"backend must be one of {BACKENDS}, got {backend!r}")
    target = Path(target).expanduser()
    done: list[tuple[Path, str]] = []
    for name, text in render_agents()[backend].items():
        path = target / name
        if not path.exists():
            action = "created"
        elif path.read_text(encoding="utf-8") == text:
            action = "unchanged"
        elif force:
            action = "overwritten"
        else:
            action = "skipped"
        if action in ("created", "overwritten") and not dry_run:
            target.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
        done.append((path, action))
    return done


def _generate() -> list[Path]:
    """Refresh the files shipped in the package (maintainers run this after editing prompts)."""
    written = []
    for backend, files in render_agents().items():
        folder = packaged_dir() / backend
        folder.mkdir(parents=True, exist_ok=True)
        for name, text in files.items():
            (folder / name).write_text(text, encoding="utf-8")
            written.append(folder / name)
    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m agentflow.workflow")
    sub = parser.add_subparsers(dest="cmd", required=True)
    sub.add_parser("list", help="list the agent files that would be produced")
    show = sub.add_parser("show", help="print one agent file")
    show.add_argument("backend", choices=BACKENDS)
    show.add_argument("name")
    inst = sub.add_parser("install", help="copy the agent files into a directory you name")
    inst.add_argument("backend", choices=BACKENDS)
    inst.add_argument("--to", required=True, help="target agents directory (no default)")
    inst.add_argument("--force", action="store_true", help="overwrite files that differ")
    inst.add_argument("--dry-run", action="store_true")
    sub.add_parser("generate", help="(maintainers) refresh the files shipped in the package")
    args = parser.parse_args(argv)

    if args.cmd == "list":
        for backend, files in render_agents().items():
            for name in files:
                print(f"{backend}/{name}")
    elif args.cmd == "show":
        files = render_agents()[args.backend]
        key = (
            args.name
            if args.name in files
            else next((n for n in files if n.rsplit(".", 1)[0] == args.name), None)
        )
        if key is None:
            print(f"no such agent: {args.name}", file=sys.stderr)
            return 1
        print(files[key], end="")
    elif args.cmd == "install":
        for path, action in install_agents(
            args.backend, args.to, force=args.force, dry_run=args.dry_run
        ):
            print(f"{action:11} {path}")
    elif args.cmd == "generate":
        for path in _generate():
            print(f"wrote {path}")
    return 0
